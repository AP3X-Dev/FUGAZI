/**
 * Return `true` if `specifier` (or its leading dotted segment) is a Python
 * stdlib module. Returns `false` for empty input.
 *
 *   isPythonStdlib('os')           → true
 *   isPythonStdlib('os.path')      → true
 *   isPythonStdlib('urllib.request') → true
 *   isPythonStdlib('requests')     → false
 *   isPythonStdlib('')             → false
 */
export function isPythonStdlib(specifier: string): boolean {
  if (specifier === '') return false;
  // Relative imports (leading dots) are never stdlib.
  if (specifier.startsWith('.')) return false;
  const dot = specifier.indexOf('.');
  const head = dot === -1 ? specifier : specifier.slice(0, dot);
  return PYTHON_STDLIB_MODULES.has(head);
}
