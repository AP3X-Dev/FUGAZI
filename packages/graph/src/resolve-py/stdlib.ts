/**
 * resolve-py/stdlib.ts — Phase 4b T321 — Python stdlib allowlist.
 *
 * Hardcoded set of Python 3.11 standard-library top-level modules. Sourced from
 * CPython's `sys.stdlib_module_names` (Python 3.11.x). For dotted imports like
 * `urllib.request` or `email.mime.text`, only the leading segment is checked
 * (`urllib`, `email`).
 *
 * Specifiers that match return `kind: 'builtin'` from the dispatcher — mirroring
 * the `node:` prefix handling for Node/Bun built-ins. The graph layer treats
 * `'builtin'` like `'external'` but with `resolvable: true`, so import-hygiene
 * and unused-deps rules don't false-positive on stdlib usage.
 *
 * The set is frozen for determinism. Additions for future Python versions
 * should land as a separate set + version-aware accessor; v1 targets 3.11+.
 *
 * Note on private modules: CPython's `sys.stdlib_module_names` includes both
 * public modules (e.g. `os`) and underscore-prefixed internal modules (`_abc`,
 * `_thread`). User code may legitimately import some of the underscore ones
 * (`_thread`, `_csv`, `_decimal`), so we keep them in the allowlist. Frozen
 * implementation modules under `_frozen_importlib` are NOT user-facing and
 * are excluded.
 */

